#!/usr/bin/env python3
"""Generate a GLS testbench include that clears X out of flops with no reset.

Gate-level sim starts every flop as X. Flops with no reset (PicoRV32's
mul_counter, for example) can stay X forever when the gates feeding them are
X-pessimistic, even though silicon settles on the first clock. This forces the
D input of every matching flop to 0 from shortly after time 0 until the
testbench sets `loaded` (end of the SPI boot, CPU still held in reset), then
releases it. That models one legal power-up state.

usage: gls_xinit.py <netlist.v> <q-net regex> > tb/gls_xinit.svh
"""
import re, sys

nl, pat = sys.argv[1], re.compile(sys.argv[2])
inst = re.compile(r"^\s*(sg13cmos5l_\w+)\s+(\S+)\s*\((.*?)\);", re.S | re.M)
pin = re.compile(r"\.(\w+)\(\s*(\\\\\S+\s|[^\s)]+)\s*\)")

def ref(n):
    n = n.strip()
    return f"dut.{n} " if n.startswith("\\") else f"dut.{n}"

d_nets = []
for cell, name, body in inst.findall(open(nl).read()):
    if not re.search(r"df|sdf|dll", cell):
        continue
    pins = {p: n for p, n in pin.findall(body)}
    q, d = pins.get("Q") or pins.get("Q_N"), pins.get("D")
    if q and d and pat.search(q) and not d.strip().startswith("1'b"):
        d_nets.append(d)

d_nets = sorted(set(d_nets))
print(f"  // generated by gls_xinit.py: {len(d_nets)} flop D inputs held at 0 until boot load ends")
print("  initial begin")
print("    #1000;")
for d in d_nets: print(f"    force {ref(d)}= 1'b0;")
print("    wait (loaded);")
for d in d_nets: print(f"    release {ref(d)};")
print("  end")
print(f"// {len(d_nets)} flops", file=sys.stderr)
